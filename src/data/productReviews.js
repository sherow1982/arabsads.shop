// دالة لتوليد تقييمات افتراضية
function generateDefaultReviews(productId) {
  const emiratiNames = [
    "أحمد الشامسي", "فاطمة المرزوقي", "خالد النعيمي", "سالم الكتبي", "مريم الظاهري",
    "راشد المهيري", "نورة السويدي", "عبدالله الحمادي", "شما المنصوري", "محمد البلوشي",
    "علي الزعابي", "حمد الشحي", "لطيفة الكعبي", "سعيد المطروشي", "عائشة الدرعي"
  ];
  
  const positiveComments = [
    "منتج ممتاز! جودة عالية وسعر مناسب",
    "والله شي خرافي! ينصح فيه بقوة",
    "استخدمته وحبيته كثير، جودة ممتازة",
    "أفضل منتج اشتريته من المتجر",
    "جودة فوق التوقعات، مشكورين",
    "منتج رائع وتوصيل سريع",
    "ما شاء الله، جودة عالية جداً",
    "استلمته بسرعة والجودة ممتازة",
    "منتج مثالي، حبيته من أول استخدام",
    "جودة ممتازة وسعر معقول"
  ];
  
  const reviews = [];
  const numReviews = 2 + (productId % 3); // 2-4 تقييمات
  
  for (let i = 0; i < numReviews; i++) {
    const rating = (productId + i) % 5 === 0 ? 4 : 5;
    const nameIndex = (productId * 3 + i * 2) % emiratiNames.length;
    const commentIndex = (productId * 2 + i) % positiveComments.length;
    const daysAgo = 5 + (productId + i * 3) % 15;
    
    const date = new Date();
    date.setDate(date.getDate() - daysAgo);
    
    reviews.push({
      name: emiratiNames[nameIndex],
      rating,
      comment: positiveComments[commentIndex],
      date: date.toISOString().split('T')[0],
      verified: true
    });
  }
  
  return reviews;
}

