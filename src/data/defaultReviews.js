// دالة لتوليد تقييمات عشوائية
function generateDefaultReviews() {
  const reviews = [];
  const numReviews = Math.floor(Math.random() * 3) + 2; // 2-4 تقييمات
  
  for (let i = 0; i < numReviews; i++) {
    const rating = Math.random() > 0.2 ? 5 : 4; // 80% تقييم 5 نجوم
    const name = emiratiNames[Math.floor(Math.random() * emiratiNames.length)];
    const comment = positiveComments[Math.floor(Math.random() * positiveComments.length)];
    const daysAgo = Math.floor(Math.random() * 20) + 1;
    const date = new Date();
    date.setDate(date.getDate() - daysAgo);
    
    reviews.push({
      name,
      rating,
      comment,
      date: date.toISOString().split('T')[0],
      verified: true
    });
  }
  
  return reviews;
}

