const fs = require('fs');

// قراءة ملف المنتجات
const productsFile = fs.readFileSync('./src/data/products.js', 'utf-8');

// استخراج المنتجات من الملف
const productsMatch = productsFile.match(/export const products = (\[[\s\S]*\]);/);
if (!productsMatch) {
  console.error('لم يتم العثور على المنتجات');
  process.exit(1);
}

const products = JSON.parse(productsMatch[1]);

console.log(`إجمالي المنتجات: ${products.length}`);

// إحصائيات
let withDescription = 0;
let withoutDescription = 0;
let missingPrice = 0;
let missingSalePrice = 0;

products.forEach(product => {
  if (product.description && product.description.trim() !== '') {
    withDescription++;
  } else {
    withoutDescription++;
  }
  
  if (!product.price) missingPrice++;
  if (!product.salePrice) missingSalePrice++;
});

console.log(`\nالإحصائيات:`);
console.log(`- منتجات بوصف: ${withDescription}`);
console.log(`- منتجات بدون وصف: ${withoutDescription}`);
console.log(`- منتجات بدون سعر: ${missingPrice}`);
console.log(`- منتجات بدون سعر مخفض: ${missingSalePrice}`);

