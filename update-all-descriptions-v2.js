// دالة لاستخراج الكلمات المفتاحية
function extractKeywords(title, category) {
  const keywords = new Set([title, category]);
  
  // كلمات مفتاحية عامة
  const generalKeywords = ['الإمارات', 'دبي', 'أبوظبي', 'الشارقة', 'شحن مجاني', 'توصيل سريع'];
  
  // كلمات مفتاحية حسب المحتوى
  const keywordMap = {
    'ساعة': ['ساعات فاخرة', 'ساعات رجالية', 'ساعات نسائية', 'ساعات أصلية', 'إكسسوارات'],
    'حقيبة': ['حقائب نسائية', 'حقائب فاخرة', 'حقائب جلد', 'إكسسوارات نسائية', 'موضة'],
    'عطر': ['عطور فاخرة', 'عطور رجالية', 'عطور نسائية', 'عطور أصلية', 'بارفان'],
    'جهاز': ['أجهزة منزلية', 'إلكترونيات', 'تقنية حديثة', 'أجهزة كهربائية'],
    'مطبخ': ['أدوات مطبخ', 'أواني طبخ', 'مطبخ عصري', 'أدوات طهي'],
    'سيارة': ['إكسسوارات سيارات', 'قطع سيارات', 'سيارات', 'إكسسوارات سيارة'],
    'أطفال': ['ألعاب أطفال', 'منتجات أطفال', 'رعاية الأطفال', 'ألعاب تعليمية'],
    'إضاءة': ['إنارة', 'ديكور', 'إضاءة LED', 'إضاءة منزلية', 'مصابيح'],
    'رولكس': ['ساعات رولكس', 'رولكس أصلية', 'ساعات سويسرية', 'ساعات فاخرة'],
    'لويس فيتون': ['حقائب لويس فيتون', 'لويس فيتون أصلية', 'حقائب فاخرة'],
    'كهربائي': ['أجهزة كهربائية', 'إلكترونيات', 'أدوات كهربائية'],
    'محمول': ['محمول', 'متنقل', 'سهل الحمل', 'portable']
  };
  
  // إضافة كلمات مفتاحية بناءً على العنوان
  for (const [key, values] of Object.entries(keywordMap)) {
    if (title.toLowerCase().includes(key.toLowerCase())) {
      values.forEach(v => keywords.add(v));
    }
  }
  
  // إضافة كلمات عامة
  generalKeywords.forEach(k => keywords.add(k));
  
  return Array.from(keywords).slice(0, 12);
}

// تحديث جميع المنتجات
let updatedCount = 0;
products.forEach((product, index) => {
  const newDescription = generateRichDescription(product);
  product.description = newDescription;
  updatedCount++;
  
  if ((index + 1) % 100 === 0) {
    console.log(`✓ تم تحديث ${index + 1} منتج...`);
  }
});

