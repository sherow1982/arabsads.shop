// دالة لتوليد وصف احترافي غني
function generateRichDescription(product) {
  const title = product.title;
  const category = product.category;
  const price = product.price;
  const salePrice = product.salePrice;
  
  let description = '';
  
  // المقدمة - ذكر اسم المنتج في السياق
  description += `اكتشف ${title} - الخيار المثالي الذي يجمع بين الجودة الفائقة والتصميم العصري المبتكر. `;
  
  // وصف تفصيلي حسب الفئة
  description += getCategoryRichDescription(title, category);
  
  // ذكر اسم المنتج مرة أخرى في السياق
  description += `\n\nلماذا تختار ${title}؟\n`;
  description += `يتميز ${title} بمواصفات استثنائية تجعله الخيار الأمثل:\n\n`;
  
  // المميزات الرئيسية
  const features = getCategoryFeatures(title, category);
  features.forEach(feature => {
    description += `✓ ${feature}\n`;
  });
  
  // معلومات السعر والعرض
  if (salePrice < price) {
    const discount = Math.round(((price - salePrice) / price) * 100);
    description += `\n💎 عرض حصري: وفر ${discount}% الآن!\n`;
    description += `السعر الخاص: ${salePrice} درهم فقط (بدلاً من ${price} درهم)\n`;
  }
  
  // الكلمات المفتاحية للبحث
  const keywords = extractKeywords(title, category);
  description += `\n🔍 كلمات البحث: ${keywords.join(' | ')}\n`;
  description += `يمكنك البحث عن ${title} باستخدام: ${keywords.slice(0, 5).join('، ')}\n`;
  
  // معلومات الشحن والضمان
  description += `\n📦 معلومات الشحن والضمان:\n`;
  description += `• شحن مجاني لجميع إمارات الدولة (دبي، أبوظبي، الشارقة، عجمان، الفجيرة، رأس الخيمة، أم القيوين)\n`;
  description += `• توصيل سريع خلال 24-48 ساعة\n`;
  description += `• ضمان الجودة والاستبدال خلال 7 أيام\n`;
  description += `• منتج أصلي 100% مع ضمان الجودة\n`;
  description += `• خدمة عملاء متاحة على مدار الساعة\n`;
  
  // دعوة للشراء
  description += `\n🛒 اطلب ${title} الآن واستمتع بتجربة تسوق آمنة ومريحة!\n`;
  
  return description;
}

